import assert from 'node:assert/strict';
import {randomUUID,randomBytes} from 'node:crypto';
const url='https://br-bold-wildflower-b5gt68sx-kennelflowapi.compute.c-7.us-east-2.aws.neon.tech';
async function api(path,method='GET',data,token) {
 const response=await fetch(url+path,{method,headers:{...(data?{'content-type':'application/json'}:{}),...(token?{authorization:'Bearer '+token}:{})},body:data?JSON.stringify(data):undefined});
 return {status:response.status,body:await response.json()};
}
const email='business-profile-'+randomUUID()+'@example.invalid';
const password=randomBytes(25).toString('hex');
assert.equal((await api('/v2/signup','POST',{email,password,name:'Original Owner',kennelName:'Initial Kennel'})).status,201);
const login=await api('/v2/login','POST',{email,password});
assert.equal(login.status,200);
const token=login.body.token;
const initial=await api('/v2/me','GET',undefined,token);
const kennelID=initial.body.kennels[0].id, userID=initial.body.user.id;
const update={kennelID,expectedEmail:email,expectedBusinessName:'Initial Kennel',email,ownerName:'New Owner',businessName:'New Kennel',phone:'304-555-0199',address:'Farm Lane',website:'https://example.org'};
const save=await api('/v2/business-profile','PATCH',update,token);
assert.equal(save.status,200,JSON.stringify(save.body));
assert.equal(save.body.kennels[0].name,'New Kennel');
const reload=await api('/v2/me','GET',undefined,token);
assert.equal(reload.body.kennels[0].address,'Farm Lane');
assert.equal(reload.body.kennels[0].phone,'304-555-0199');
assert.equal(reload.body.user.name,'New Owner');
assert.equal(reload.body.user.id,userID);
assert.equal((await api('/v2/business-profile','PATCH',update,token)).status,409);
console.log('PASS profile update, reload, stable account ID, stale conflict');
const newEmail=email.replace('business-profile-','business-updated-');
const changed={...update,expectedBusinessName:'New Kennel',email:newEmail,currentPassword:password};
const changedResult=await api('/v2/business-profile','PATCH',changed,token);
assert.equal(changedResult.status,200,JSON.stringify(changedResult.body));
assert.equal(changedResult.body.user.id,userID);
assert.equal(changedResult.body.user.email,newEmail);
assert.equal((await api('/v2/login','POST',{email,password})).status,401);
assert.equal((await api('/v2/login','POST',{email:newEmail,password})).status,200);
const withoutPassword={...changed,expectedEmail:newEmail,email:email};
delete withoutPassword.currentPassword;
assert.equal((await api('/v2/business-profile','PATCH',withoutPassword,token)).status,400);
console.log('PASS email changes, preserved owner identity, current-password requirement');
